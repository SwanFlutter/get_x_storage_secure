// Regenerates the JNI bindings for the Android vault helper:
//
//     dart run tool/jnigen.dart
//
// The helper is Kotlin, so the summarizer reads its class files rather than its
// source. Build them first:
//
//     cd example/android
//     ./gradlew :get_x_storage_secure:compileDebugKotlin
//
// `android.jar` supplies `android.content.Context`, the parameter the helper uses
// to reach `noBackupFilesDir` so Dart never owns that path logic.
import 'dart:io';

import 'package:jnigen/jnigen.dart';

Uri _androidSdkRoot(Uri packageRoot) {
  final String? fromEnv =
      Platform.environment['ANDROID_SDK_ROOT'] ??
      Platform.environment['ANDROID_HOME'];
  if (fromEnv != null && fromEnv.isNotEmpty) {
    return Uri.directory(fromEnv);
  }
  // Flutter writes the SDK location into the plugin's own local.properties.
  final File properties = File.fromUri(
    packageRoot.resolve('android/local.properties'),
  );
  for (final String line in properties.readAsLinesSync()) {
    final List<String> parts = line.split('=');
    if (parts.first.trim() == 'sdk.dir') {
      return Uri.directory(
        parts.sublist(1).join('=').trim().replaceAll(r'\', '/'),
      );
    }
  }
  throw StateError('Set ANDROID_HOME or fix android/local.properties.');
}

Future<void> main() async {
  final Uri packageRoot = Platform.script.resolve('../');
  final JniGenerator generator = JniGenerator(
    input: Input(
      classes: <String>[
        'io.github.swanflutter.get_x_storage_secure.vault.VaultKeyStore',
      ],
      classPath: <Uri>[
        packageRoot.resolve(
          'example/build/get_x_storage_secure/tmp/kotlin-classes/debug/',
        ),
      ],
      androidSdk: AndroidSdk(
        versions: <int>[36, 35, 34, 33],
        sdkRoot: _androidSdkRoot(packageRoot),
      ),
    ),
    output: Output(
      dart: DartOutput(
        path: packageRoot.resolve('lib/src/vault/android_bindings.dart'),
        structure: OutputStructure.singleFile,
      ),
      // Without a stub, `android.content.Context` is typed as JObject in the
      // generated methods, which is what jni_flutter's androidApplicationContext
      // already is. A stub would have a private constructor Dart cannot call.
      generateStubs: false,
      preamble:
          '// Generated by tool/jnigen.dart. Run `dart run tool/jnigen.dart`\n'
          '// after changing the Kotlin helper; do not edit by hand.\n'
          '// ignore_for_file: type=lint\n',
    ),
  );
  await generator.generate();
}
